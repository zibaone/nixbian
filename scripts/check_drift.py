#!/usr/bin/env python3
"""Nixbian anti-drift guard.

`metadata/nix/library.nix` and `metadata/nix/firmware.nix` are verbatim
copies of the `src/armbian_extractor/templates/{library,firmware}.nix` templates
(see `NixGenerator.write_library_nix`). `metadata/` is GENERATED: any manual
edit there creates silent drift — it is overwritten on the next
regeneration and has already nearly broken the entire pipeline.

This script regenerates the result of `write_library_nix()` in a temporary
directory (NixGenerator instance with a fake src path) and compares
with `metadata/nix/`. Non-zero exit + readable diff on mismatch.

Usage:
    python3 scripts/check_drift.py [--metadata-dir metadata]

Exit codes:
    0 — no drift
    1 — drift detected (metadata out of sync with templates)
    2 — runtime error (generator import, missing template, ...)
"""

import argparse
import difflib
import sys
import tempfile
import traceback
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent


class CheckError(RuntimeError):
    """Guard runtime error (≠ drift)."""


def _display(path: Path) -> str:
    """Path displayed relative to the repo when possible."""
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def _import_nix_generator():
    """Import NixGenerator from src/armbian_extractor/generator.py."""
    src_dir = REPO_ROOT / "src"
    if str(src_dir) not in sys.path:
        sys.path.insert(0, str(src_dir))
    try:
        from armbian_extractor.generator import NixGenerator
    except Exception as exc:  # SyntaxError if generator.py is being edited
        raise CheckError(
            "cannot import src/armbian_extractor/generator.py "
            f"({exc.__class__.__name__}: {exc}). "
            "Check that generator.py is valid (it must import without error)."
        ) from exc
    return NixGenerator


def regenerate(workdir: Path) -> Path:
    """Regenerate write_library_nix() in `workdir` and return the produced nix folder.

    The src path passed to NixGenerator is fake: write_library_nix() never
    reads the Armbian sources, it only copies the package templates.
    """
    nix_generator = _import_nix_generator()
    fake_src = workdir / "fake-armbian-src"
    fake_src.mkdir(parents=True, exist_ok=True)
    generator = nix_generator(fake_src, workdir / "out")
    generator.write_library_nix()
    return workdir / "out" / "nix"


def compare(regenerated_nix: Path, metadata_nix: Path) -> list[tuple[str, str]]:
    """Compare the files produced by write_library_nix() with metadata/nix/.

    Return a list [(relative path, report)] — one entry per drifted
    file (different content or absent from metadata/).
    """
    produced = sorted(p for p in regenerated_nix.rglob("*") if p.is_file())
    if not produced:
        raise CheckError(
            "write_library_nix() produced no files — "
            "missing templates in src/armbian_extractor/templates/?"
        )

    problems: list[tuple[str, str]] = []
    for produced_file in produced:
        rel = produced_file.relative_to(regenerated_nix)
        reference = metadata_nix / rel
        if not reference.is_file():
            problems.append(
                (
                    str(rel),
                    f"absent from {metadata_nix} (file produced by the generator but never committed)",
                )
            )
            continue
        regenerated_lines = produced_file.read_text(encoding="utf-8").splitlines()
        reference_lines = reference.read_text(encoding="utf-8").splitlines()
        if regenerated_lines != reference_lines:
            diff = "\n".join(
                difflib.unified_diff(
                    reference_lines,
                    regenerated_lines,
                    fromfile=f"{rel} (current metadata/)",
                    tofile=f"{rel} (regenerated from templates)",
                    lineterm="",
                )
            )
            problems.append((str(rel), diff))
    return problems


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        prog="check-drift",
        description=(
            "Checks that metadata/nix/ has not drifted from the templates "
            "(files generated by NixGenerator.write_library_nix)."
        ),
    )
    parser.add_argument(
        "--metadata-dir",
        default=str(REPO_ROOT / "metadata"),
        help="metadata directory to check (default: <repo>/metadata)",
    )
    args = parser.parse_args(argv)

    metadata_nix = Path(args.metadata_dir).resolve() / "nix"
    if not metadata_nix.is_dir():
        print(f"❌ {metadata_nix} not found.", file=sys.stderr)
        return 2

    try:
        with tempfile.TemporaryDirectory(prefix="nixbian-check-drift-") as tmp:
            regenerated_nix = regenerate(Path(tmp))
            problems = compare(regenerated_nix, metadata_nix)
            compared = sorted(
                f"{_display(metadata_nix)}/{p.relative_to(regenerated_nix)}"
                for p in regenerated_nix.rglob("*")
                if p.is_file()
            )
    except CheckError as exc:
        print(f"❌ {exc}", file=sys.stderr)
        return 2
    except Exception:
        print("❌ unexpected error during regeneration:", file=sys.stderr)
        traceback.print_exc()
        return 2

    if problems:
        print(
            "❌ Drift detected: the following files no longer match the templates."
        )
        print("   metadata/ is GENERATED — never edit it by hand;")
        print(
            "   regenerate instead of patching (otherwise the next regeneration overwrites the changes)."
        )
        print()
        for rel, report in problems:
            print(f"--- {rel} ---")
            print(report)
            print()
        return 1

    print(f"✅ No drift: {', '.join(compared)} identical to the templates.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
