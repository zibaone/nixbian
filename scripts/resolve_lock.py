#!/usr/bin/env python3
"""Resolve nvfetcher.sources.toml (branches) → nvfetcher.lock.toml (commits)
and prefetch SHA256 for sources whose rev changed."""

import os, subprocess, sys, time, tomllib
from pathlib import Path

from prefetch import DEFAULT_JOBS, prefetch_many

sources_path = Path("metadata/nvfetcher.sources.toml")
lock_path = Path("metadata/nvfetcher.lock.toml")
generated_path = Path("metadata/sources/generated.nix")
changed_path = Path("metadata/sources/changed.json")

with open(sources_path, "rb") as f:
    cfg = tomllib.load(f)

# Load old lock to detect changes
old_lock = {}
if lock_path.exists():
    with open(lock_path, "rb") as f:
        old = tomllib.load(f)
        old_lock = {n: e.get("rev", "") for n, e in old.items()}

# Load old generated.nix hashes
old_hashes = {}
if generated_path.exists():
    try:
        import re

        text = generated_path.read_text()
        for m in re.finditer(
            r'(\S+)\s*=\s*\{[^}]*?rev\s*=\s*"([^"]+)"[^}]*?sha256\s*=\s*"([^"]+)"', text
        ):
            old_hashes[m.group(1)] = {"rev": m.group(2), "sha256": m.group(3)}
    except Exception:
        pass

changed_entries = []
changed = 0
seen = {}

for name, entry in sorted(cfg.items()):
    rev = entry.get("rev", "")
    if not rev.startswith("refs/heads/"):
        continue
    url = entry.get("fetch", {}).get("git", "")
    if not url:
        continue
    key = (url, rev)
    if key not in seen:
        commit = None
        for attempt in range(3):
            try:
                result = subprocess.run(
                    ["git", "ls-remote", url, rev],
                    capture_output=True,
                    text=True,
                    timeout=60,
                )
                c = result.stdout.split()[0] if result.stdout else ""
                if c and len(c) == 40:
                    commit = c
                    break
            except subprocess.TimeoutExpired:
                if attempt < 2:
                    time.sleep(5 * (attempt + 1))
                    continue
            except Exception as e:
                print(f"  ⚠️  {name}: {e}", file=sys.stderr)
                break
        if commit:
            seen[key] = commit
        else:
            seen[key] = None
            print(f"  ⚠️  {name}: skipped after 3 attempts", file=sys.stderr)

    commit = seen.get(key)
    if commit:
        entry["rev"] = commit
        entry["src"] = {"manual": commit}
        changed += 1

        # Check if rev actually changed
        old_rev = old_lock.get(name, "")
        if commit != old_rev and commit != old_rev.replace("refs/heads/", ""):
            changed_entries.append({"name": name, "url": url, "rev": commit})
    else:
        if name in cfg:
            del cfg[name]

# Write lock file
out_lines = []
for name, entry in sorted(cfg.items()):
    git = entry.get("fetch", {}).get("git", "")
    rev = entry.get("rev", "")
    manual = entry.get("src", {}).get("manual", rev)
    out_lines.append(f"[{name}]")
    out_lines.append(f'src.manual = "{manual}"')
    out_lines.append(f'fetch.git = "{git}"')
    out_lines.append(f'rev = "{rev}"')
    out_lines.append("")

lock_path.write_text("\n".join(out_lines))
print(f"✅ {changed} branch(es) resolved → {lock_path}")

# Prefetch hashes for changed sources
if changed_entries:
    # Sources are independent: prefetch them in parallel, otherwise a kernel
    # snapshot per changed branch does not fit in a CI job. `jobs` is tunable
    # for a slow network.
    new_hashes = dict(old_hashes)
    prefetched = prefetch_many(
        changed_entries,
        jobs=os.environ.get("NIXBIAN_PREFETCH_JOBS", DEFAULT_JOBS),
    )
    new_hashes.update(prefetched)

    # Regenerate generated.nix
    gen_lines = [
        "# This file was generated by resolve_lock.py",
        "# Please do not modify it manually.",
        "{",
        "  fetchgit,",
        "  fetchurl,",
        "  fetchFromGitHub,",
        "  dockerTools,",
        "}:",
        "{",
    ]
    for name, entry in sorted(cfg.items()):
        url = entry.get("fetch", {}).get("git", "")
        rev = entry.get("rev", "")
        if not url or not rev:
            continue
        h = new_hashes.get(name, {})
        sha256 = h.get("sha256", "")
        if not sha256:
            continue
        pname = name.replace("_", "-")
        gen_lines.append(f"  {name} = {{")
        gen_lines.append(f'    pname = "{pname}";')
        gen_lines.append(f'    version = "{rev}";')
        gen_lines.append(f"    src = fetchgit {{")
        gen_lines.append(f'      url = "{url}";')
        gen_lines.append(f'      rev = "{rev}";')
        gen_lines.append(f"      fetchSubmodules = false;")
        gen_lines.append(f"      deepClone = false;")
        gen_lines.append(f"      leaveDotGit = false;")
        gen_lines.append(f"      sparseCheckout = [ ];")
        gen_lines.append(f'      sha256 = "{sha256}";')
        gen_lines.append(f"    }};")
        gen_lines.append(f"  }};")
    gen_lines.append("}")
    generated_path.parent.mkdir(parents=True, exist_ok=True)
    generated_path.write_text("\n".join(gen_lines) + "\n")
    print(f"✅ generated.nix updated ({len(new_hashes)} sources)")
else:
    print("ℹ️  No rev changes — no prefetch needed.")
